const M_SHORT = ['sty', 'lut', 'mar', 'kwi', 'maj', 'cze', 'lip', 'sie', 'wrz', 'paź', 'lis', 'gru']
const M_FULL = [
  'Styczeń', 'Luty', 'Marzec', 'Kwiecień', 'Maj', 'Czerwiec',
  'Lipiec', 'Sierpień', 'Wrzesień', 'Październik', 'Listopad', 'Grudzień',
]

export function fmtDatePl(iso) {
  const d = new Date(iso)
  return `${d.getDate()} ${M_SHORT[d.getMonth()]} ${d.getFullYear()}`
}

export function fmtDatePlShort(iso) {
  const d = new Date(iso)
  return `${d.getDate()} ${M_SHORT[d.getMonth()]}`
}

// "2026-08" → "Sierpień 2026"
export function fmtMonthPl(key) {
  const [y, m] = key.split('-')
  return `${M_FULL[Number(m) - 1]} ${y}`
}

export function monthShortPl(i) {
  return M_SHORT[i]
}

// age like "2 lata 3 mies."
export function agePl(birthISO, onISO) {
  if (!birthISO) return '—'
  const b = new Date(birthISO)
  const d = onISO ? new Date(onISO) : new Date()
  let months = (d.getFullYear() - b.getFullYear()) * 12 + (d.getMonth() - b.getMonth())
  if (d.getDate() < b.getDate()) months--
  if (months < 0) months = 0
  const y = Math.floor(months / 12)
  const m = months % 12
  if (y <= 0) return `${m} mies.`
  const w = y === 1 ? 'rok' : y < 5 ? 'lata' : 'lat'
  return m ? `${y} ${w} ${m} mies.` : `${y} ${w}`
}

// Polish number formatting (comma decimal, thin thousands)
export function numPl(n, digits = 0) {
  if (n === null || n === undefined || Number.isNaN(Number(n))) return '—'
  return Number(n).toLocaleString('pl-PL', { maximumFractionDigits: digits })
}

export function unitPl(unit) {
  if (unit === 'g') return 'g'
  if (unit === 'pcs') return 'szt.'
  if (unit === 'portion') return 'porcji'
  return ''
}
